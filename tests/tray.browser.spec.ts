import { test, expect } from '@playwright/test';

test('tray hides missing shapes and drag drops place or snap back without mutation', async ({ page }) => {
  await page.addInitScript(() => { window.confirm = () => false; });
  await page.goto('/');
  await page.locator('#edit-puzzle').click();
  await page.locator('#draft-free').check();
  await page.locator('#draft-recovery').selectOption('tray');
  await page.locator('#draft-board button[aria-label^="Remove"]:enabled').first().click();
  await page.locator('#draft-board button[aria-label^="Remove"]:enabled').first().click();
  await page.getByRole('button', {name:'Save changes',exact:true}).click();
  await expect(page.locator('#play-screen')).toBeVisible();
  await expect(page.locator('#inventory')).toBeHidden();
  await expect(page.locator('.unknown-piece')).toHaveCount(2);
  await expect(page.locator('.unknown-piece svg')).toHaveCount(0);
  const board = await page.locator('#board').boundingBox();
  const tray = await page.locator('.inventory-panel').boundingBox();
  expect(tray!.x).toBeGreaterThan(board!.x + board!.width);
  await page.locator('#piece-tray .unknown-piece').first().click({button:'right'}); await page.getByRole('menuitem',{name:'Give piece to players',exact:true}).click();
  await expect(page.locator('.unknown-piece')).toHaveCount(1);
  await expect(page.locator('#piece-tray button svg')).toHaveCount(1);
  await page.locator('#piece-tray button').scrollIntoViewIfNeeded();
  const card = await page.locator('#piece-tray button').boundingBox();
  await page.mouse.move(card!.x+44,card!.y+40); await page.mouse.down();
  await page.mouse.move(card!.x+160,card!.y+40,{steps:8}); await page.mouse.up();
  await expect(page.locator('.dragged-piece')).toHaveCount(0);
  await expect(page.locator('#piece-tray button')).toHaveCount(1);
  const socketIndex = await page.locator('#board button.empty').first().getAttribute('data-index');
  const socket = page.locator('#board button[data-index="' + socketIndex + '"]');
  await page.locator('#piece-tray button').scrollIntoViewIfNeeded();
  const source = await page.locator('#piece-tray button').boundingBox();
  await page.mouse.move(source!.x+44,source!.y+40); await page.mouse.down();
  await page.mouse.wheel(0,-650);
  await expect.poll(() => page.evaluate(() => scrollY)).toBe(0);
  await expect.poll(async () => (await socket.boundingBox())!.y).toBeGreaterThanOrEqual(0);
  const target = await socket.boundingBox();
  await page.mouse.move(target!.x+target!.width/2,target!.y+target!.height/2,{steps:10}); await page.mouse.up();
  await expect(socket).toHaveClass(/occupied/);
  await expect(page.locator('#piece-tray button')).toHaveCount(0);
  await expect(page.locator('.unknown-piece')).toHaveCount(1);
  await page.screenshot({path:'docs/evidence/tray-drag-review.png',fullPage:true});
});
